import { chromium } from '@playwright/test'
import { prepare, openDemo, go } from './lib.mjs'
const OUT = process.argv[2]
const browser = await chromium.launch({ args: ['--lang=en-GB'], env: { ...process.env, LANG: 'en_GB.UTF-8', LC_ALL: 'en_GB.UTF-8', LANGUAGE: 'en_GB' } })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'en-GB', timezoneId: 'Europe/Madrid' })
await prepare(ctx)
const page = await openDemo(ctx, { time: '2026-12-09T05:55:00Z', path: '/calendar?tab=routine' })
const shot = async n => { await page.waitForTimeout(900); await page.screenshot({ path: `${OUT}/y_${n}.png` }) }
await page.getByRole('button', { name: 'Add an activity' }).click()
const d = page.getByRole('dialog', { name: 'Add an activity' })
await d.getByLabel('Name').fill('Unlock, lights and terrace')
await shot('dialog')
console.log('days pressed:', await d.getByRole('group', { name: 'Days' }).getByRole('button').evaluateAll(bs => bs.map(b => b.getAttribute('aria-label') + ':' + b.getAttribute('aria-pressed'))))
await d.getByLabel('From (optional)').fill('06:55')
await d.getByRole('button', { name: 'Add' }).click()
await page.waitForTimeout(800)
await go(page, '/')
await page.waitForTimeout(1200)
const r = page.getByRole('region', { name: 'Today’s routine' })
console.log('routine region:', await r.count(), await r.textContent().catch(() => ''))
await r.scrollIntoViewIfNeeded().catch(() => {})
await shot('today_routine')
const music = page.getByRole('region', { name: 'Café music' })
await music.scrollIntoViewIfNeeded().catch(() => {})
console.log('music:', (await music.textContent().catch(() => '')).slice(0, 200))
const play = music.getByRole('button', { name: 'Play' }).first()
if (await play.count()) { await play.click(); await page.waitForTimeout(1200); console.log('after play:', (await music.textContent()).slice(0, 200)) }
await shot('music')
await go(page, '/messages'); await page.waitForTimeout(1200)
await page.getByText('Do you have oat milk', { exact: false }).first().click()
await page.waitForTimeout(800); await shot('msg_open')
await go(page, '/stock'); await page.waitForTimeout(800)
await page.getByRole('tab', { name: /Order list/ }).click(); await page.waitForTimeout(800); await shot('order')
await browser.close()
